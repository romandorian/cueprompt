if any(len(values) != len(ENGLISH) for values in TRANSLATIONS.values()):
    raise ValueError('Every scene-guide locale must translate every visible phrase')


def localize(page, locale, slug):
    if slug not in SCENE_GUIDE_SLUGS or locale not in TRANSLATIONS:
        return page
    for source, target in sorted(zip(ENGLISH, TRANSLATIONS[locale]), key=lambda item: len(item[0]), reverse=True):
        page = page.replace(source, target)
    return page


def descriptions(locale):
    """Return scene-specific SEO descriptions in manifest order."""
    values = TRANSLATIONS.get(locale)
    return dict(zip(SCENE_GUIDE_SLUGS, values[1:7])) if values else {}
