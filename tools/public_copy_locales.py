if any(len(values) != len(PHRASES) for values in VALUES.values()):
    raise ValueError('Every public-copy locale must translate every shared phrase')


def localize(page, locale):
    values = VALUES.get(locale)
    if not values:
        return page
    for source, target in sorted(zip(PHRASES, values), key=lambda item: len(item[0]), reverse=True):
        page = page.replace(source, target)
    return page
