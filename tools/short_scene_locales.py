def _taiwan(text):
    text = _to_zh_tw(text)
    fixes = {
        'Shorts 工作流程': 'YouTube Shorts 工作流程', 'TIKTOK 工作流程': 'TIKTOK 工作流程',
        '直向': '直式', '豎屏': '直式', '竖屏': '直式', '信息流': '動態消息',
        '貼文和發布文案': '貼文與發布文案', '話題標籤': '主題標籤',
        '補充畫面': 'B-roll 畫面', '行動號召': '行動呼籲', '首幀': '第一個畫面',
        '封面幀': '封面畫面', '主页': '個人檔案', '網格': '版面網格',
        'Short 中': 'Shorts 中', '一條 Short': '一支 Short', '每條 Short': '每支 Short',
        '下一條影片': '下一支影片', '导出': '匯出', '屏幕': '螢幕', '控件': '控制項',
        '创建': '建立', '用户': '使用者', '观看': '觀看', '怎样': '如何', '吗': '嗎',
    }
    for source, target in fixes.items():
        text = text.replace(source, target)
    return text


ZH_TW = {slug: tuple((source, _taiwan(target)) for source, target in pairs) for slug, pairs in ZH_CN.items()}
COMMON_TW = {source: _taiwan(target) for source, target in COMMON.items()}


def localize(page, locale, slug):
    packs = {'zh-CN': (COMMON, ZH_CN), 'zh-TW': (COMMON_TW, ZH_TW)}
    if locale not in packs or slug not in packs[locale][1]:
        return page
    common, scenes = packs[locale]
    for source, target in sorted((*common.items(), *scenes[slug]), key=lambda item: len(item[0]), reverse=True):
        page = page.replace(source, target)
    return page
